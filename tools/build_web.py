#!/usr/bin/env python3
"""Prepares web/ for deployment from the book packs.

- Public-domain packs go to web/public/books/ (served as static files).
- Private packs (rights.status == "private-test") go to web/api/_private/, served only through the
  passcode-gated /api/pack function, never as static files.
- Writes web/public/books/index.json with "access": "private" on gated books.
- Stamps a content hash into web/public/sw.js so every deploy refreshes the offline cache.

Run after content/src/build.py:  python3 tools/build_web.py
"""
import hashlib
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "android", "app", "src", "main", "assets", "books")
WEB = os.path.join(ROOT, "web")
PUB_BOOKS = os.path.join(WEB, "public", "books")
PRIVATE = os.path.join(WEB, "api", "_private")


def main():
    with open(os.path.join(SRC, "index.json"), encoding="utf-8") as f:
        index = json.load(f)
    os.makedirs(PUB_BOOKS, exist_ok=True)
    os.makedirs(PRIVATE, exist_ok=True)
    for d in (PUB_BOOKS, PRIVATE):
        for name in os.listdir(d):
            if name.endswith(".json") or name == "index.js":
                os.remove(os.path.join(d, name))
    private_ids = []
    for b in index["books"]:
        if b.get("status") != "ready":
            continue
        with open(os.path.join(SRC, b["file"]), encoding="utf-8") as f:
            pack = json.load(f)
        if pack.get("rights", {}).get("status") == "private-test":
            b["access"] = "private"
            shutil.copyfile(os.path.join(SRC, b["file"]), os.path.join(PRIVATE, b["file"]))
            private_ids.append((b["id"], b["file"]))
        else:
            b["access"] = "public"
            shutil.copyfile(os.path.join(SRC, b["file"]), os.path.join(PUB_BOOKS, b["file"]))
    with open(os.path.join(PUB_BOOKS, "index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=1)
    lines = ["// Generated by tools/build_web.py: private packs, bundled into the /api/pack function only.", "module.exports = {"]
    lines += [f'  "{i}": require("./{fn}"),' for i, fn in private_ids]
    lines.append("};")
    with open(os.path.join(PRIVATE, "index.js"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    h = hashlib.sha1()
    for base, _, files in sorted(os.walk(os.path.join(WEB, "public"))):
        for name in sorted(files):
            if name == "sw.js":
                continue
            with open(os.path.join(base, name), "rb") as f:
                h.update(name.encode() + f.read())
    for _, fn in private_ids:
        with open(os.path.join(PRIVATE, fn), "rb") as f:
            h.update(f.read())
    version = "bookreel-" + h.hexdigest()[:10]
    sw = os.path.join(WEB, "public", "sw.js")
    with open(sw, encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r'const VERSION = "[^"]*";', f'const VERSION = "{version}";', text)
    with open(sw, "w", encoding="utf-8") as f:
        f.write(text)
    ready = [b["id"] + ("*" if b.get("access") == "private" else "") for b in index["books"] if b.get("status") == "ready"]
    print(f"web: {len(ready)} ready books ({', '.join(ready)}; * = private), cache {version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
